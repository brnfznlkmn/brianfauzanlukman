function portfolioText(indonesian) {
    return document.documentElement.lang === 'en'
        ? portfolioTranslations[indonesian] || indonesian
        : indonesian;
}

function readLanguagePreference() {
    try {
        const saved = localStorage.getItem('language');
        return saved === 'id' || saved === 'en' ? saved : null;
    } catch {
        return null;
    }
}

function browserLanguageDefault() {
    return (navigator.languages || [navigator.language]).some(language => /^(id|in)(-|$)|-ID$/i.test(language)) ? 'id' : 'en';
}

async function detectVisitorLanguage() {
    try {
        const cached = JSON.parse(sessionStorage.getItem('visitor-country'));
        if (cached && /^[A-Z]{2}$/.test(cached.code) && Date.now() - cached.time < 21600000) {
            return cached.code === 'ID' ? 'id' : 'en';
        }
    } catch { /* Country detection also works when browser storage is unavailable. */ }

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2500);
    try {
        const response = await fetch('https://ipwho.is/?fields=success,country_code', {
            signal: controller.signal,
            credentials: 'omit',
            referrerPolicy: 'no-referrer'
        });
        if (!response.ok) return null;
        const country = await response.json();
        if (!country.success || !/^[A-Z]{2}$/.test(country.country_code)) return null;
        try {
            sessionStorage.setItem('visitor-country', JSON.stringify({ code: country.country_code, time: Date.now() }));
        } catch { /* A failed cache write should not block the detected language. */ }
        return country.country_code === 'ID' ? 'id' : 'en';
    } catch {
        return null;
    } finally {
        clearTimeout(timeout);
    }
}

function animateLanguageLayout(elements, update, enabled) {
    const before = enabled ? Array.from(elements).flatMap(element => {
        if (!element.animate || !element.getBoundingClientRect) return [];
        const rect = element.getBoundingClientRect();
        const display = getComputedStyle(element).display;
        return rect.width && rect.height && display !== 'inline' && display !== 'none'
            ? [{ element, width: rect.width, height: rect.height }]
            : [];
    }) : [];

    update();
    // Read all final sizes before starting animations, so nested boxes share one layout.
    const resized = before.map(box => ({ ...box, target: box.element.getBoundingClientRect() }));
    const animations = resized.flatMap(({ element, width, height, target }) => {
        const from = {};
        const to = {};
        if (Math.abs(height - target.height) > 0.5) {
            from.height = `${height}px`;
            to.height = `${target.height}px`;
        }
        if (Math.abs(width - target.width) > 0.5) {
            from.width = `${width}px`;
            to.width = `${target.width}px`;
            // Narrow intermediate widths must not add a line and grow the box.
            from.height = `${height}px`;
            to.height = `${target.height}px`;
        }
        if (!Object.keys(from).length) return [];
        from.overflow = 'clip';
        to.overflow = 'clip';
        return [element.animate([from, to], {
            duration: 650,
            easing: 'cubic-bezier(0.4, 0, 0.2, 1)'
        }).finished.catch(() => {})];
    });
    return Promise.all(animations);
}

function initLanguageToggle() {
    const button = document.getElementById('language-toggle');
    if (!button) return;
    const root = document.documentElement;
    const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
    const eraseDuration = 600;
    const pauseDuration = 150;
    const typingDuration = 1450;
    const animationDuration = eraseDuration + pauseDuration + typingDuration;
    const ease = progress => progress * progress * (3 - 2 * progress);
    const status = document.getElementById('language-status');
    const copies = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        if (node.parentElement.closest('script, style, svg, #language-toggle, #language-status')) continue;
        const original = node.textContent.replace(/\s+/g, ' ').trim();
        if (Object.hasOwn(portfolioTranslations, original)) {
            const leading = node.textContent.match(/^\s*/)[0];
            const trailing = node.textContent.match(/\s*$/)[0];
            copies.push({ node, id: node.textContent, en: leading + portfolioTranslations[original] + trailing });
        }
    }
    const attributes = [];
    document.querySelectorAll('[aria-label], [alt], [placeholder], meta[name="description"]').forEach(element => {
        ['aria-label', 'alt', 'placeholder', 'content'].forEach(attribute => {
            const value = element.getAttribute(attribute);
            if (Object.hasOwn(portfolioTranslations, value)) attributes.push({ element, attribute, id: value });
        });
    });
    const layoutElements = new Set([
        ...copies.map(copy => copy.node.parentElement),
        ...document.querySelectorAll('.navbar, main section, .container, .hero-content, .hero-image-container, .portrait figcaption, .hero-cta-group, .hero-note, .about-overview-grid, .about-details-grid, .about-stats-grid, .skills-grid, .contact-grid, .timeline-item, .edu-card, .social-card, .stat-card, .contact-form-card, .footer-content, .nav-container, .nav-right-group, .nav-menu ul')
    ]);

    let manualChoice = Boolean(readLanguagePreference());
    let changingLanguage = false;
    const updateControls = language => {
        root.lang = language;
        button.dataset.language = language;
        button.setAttribute('aria-label', language === 'id' ? 'Ganti bahasa ke English' : 'Switch language to Bahasa Indonesia');
        button.title = language === 'id' ? 'Switch to English' : 'Ganti ke Bahasa Indonesia';
        attributes.forEach(({ element, attribute, id }) => element.setAttribute(attribute, portfolioText(id)));
        document.querySelectorAll('[data-translation]').forEach(element => {
            element.textContent = portfolioText(element.dataset.translation);
        });
        const mobileToggle = document.getElementById('mobile-toggle');
        mobileToggle?.setAttribute('aria-label', portfolioText(mobileToggle.getAttribute('aria-expanded') === 'true' ? 'Tutup menu navigasi' : 'Buka menu navigasi'));
    };

    const changeLanguage = async (language, animate) => {
        if (changingLanguage || (language === root.lang && button.dataset.language)) return;
        changingLanguage = true;
        updateControls(language);
        const animatedCopies = [];
        animateLanguageLayout(layoutElements, () => copies.forEach(copy => {
            const target = copy[language];
            const parent = copy.node.parentElement;
            const rect = parent.getBoundingClientRect();
            const visible = rect.bottom > 0 && rect.top < window.innerHeight && rect.width > 0 && rect.height > 0;
            if (!animate || reducedMotion.matches || !visible) {
                copy.node.textContent = target;
                return;
            }
            // Invisible full texts keep the layout stable while visible characters change.
            const wrapper = document.createElement('span');
            wrapper.className = 'language-copy';
            const final = document.createElement('span');
            final.className = 'language-copy-final';
            final.textContent = target;
            const previous = document.createElement('span');
            previous.className = 'language-copy-previous';
            previous.setAttribute('aria-hidden', 'true');
            previous.textContent = copy.node.textContent;
            const visual = document.createElement('span');
            visual.className = 'language-copy-visual';
            visual.setAttribute('aria-hidden', 'true');
            visual.textContent = copy.node.textContent;
            wrapper.append(final, previous, visual);
            copy.node.replaceWith(wrapper);
            animatedCopies.push({ copy, wrapper, visual, before: Array.from(previous.textContent), after: Array.from(target) });
        }), animate && !reducedMotion.matches);

        if (animatedCopies.length) {
            button.setAttribute('aria-busy', 'true');
            await new Promise(resolve => {
                let started;
                const frame = time => {
                    started ??= time;
                    const elapsed = time - started;
                    const erasing = Math.min(1, elapsed / eraseDuration);
                    const typingElapsed = Math.max(0, elapsed - eraseDuration - pauseDuration);
                    const typing = Math.min(1, typingElapsed / typingDuration);
                    animatedCopies.forEach(({ visual, before, after }) => {
                        const characters = elapsed < eraseDuration
                            ? before.slice(0, Math.ceil(before.length * (1 - ease(erasing))))
                            : after.slice(0, Math.floor(after.length * ease(typing)));
                        visual.textContent = characters.join('') || '\u200b';
                        visual.style.opacity = String(elapsed < eraseDuration
                            ? 1 - ease(erasing)
                            : ease(Math.min(1, typingElapsed / 500)));
                    });
                    if (elapsed < animationDuration && !reducedMotion.matches) requestAnimationFrame(frame);
                    else resolve();
                };
                requestAnimationFrame(frame);
            });
            await animateLanguageLayout(layoutElements, () => animatedCopies.forEach(({ copy, wrapper }) => {
                copy.node.textContent = copy[language];
                wrapper.replaceWith(copy.node);
            }), !reducedMotion.matches);
            button.removeAttribute('aria-busy');
        }
        changingLanguage = false;
        if (animate) status.textContent = language === 'id' ? 'Bahasa Indonesia dipilih.' : 'English selected.';
    };

    button.addEventListener('click', () => {
        if (changingLanguage) return;
        manualChoice = true;
        const language = root.lang === 'id' ? 'en' : 'id';
        try { localStorage.setItem('language', language); } catch { /* Keep the choice for this visit. */ }
        changeLanguage(language, true);
    });
    changeLanguage(readLanguagePreference() || browserLanguageDefault(), false);
    if (!manualChoice) {
        detectVisitorLanguage().then(language => {
            if (language && !manualChoice) changeLanguage(language, true);
        });
    }
}

document.addEventListener('DOMContentLoaded', initLanguageToggle);
